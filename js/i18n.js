// Function to set application language dynamically
function setLanguage(lang) {
  // Save selection
  localStorage.setItem('language', lang);
  document.documentElement.setAttribute('lang', lang);
  
  // Update text nodes with data-i18n attributes
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      // Handle Input/Textarea Placeholders if data-i18n is used directly on them
      if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
        if (element.hasAttribute('placeholder')) {
          element.setAttribute('placeholder', translations[lang][key]);
        }
      } 
      // Handle Select standard options
      else if (element.tagName === 'OPTION') {
        element.textContent = translations[lang][key];
      }
      // General HTML translation
      else {
        element.innerHTML = translations[lang][key];
      }
    }
  });

  // Update placeholder attributes using dedicated data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    const key = element.getAttribute('data-i18n-placeholder');
    if (translations[lang] && translations[lang][key]) {
      element.setAttribute('placeholder', translations[lang][key]);
    }
  });

  // Keep switcher UI buttons active class synchronized
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });
}

// Export dictionary & trigger loader globally
window.setLanguage = setLanguage;
window.translations = translations;

document.addEventListener('DOMContentLoaded', () => {
  // Retrieve previous settings, default to 'en'
  const savedLang = localStorage.getItem('language') || 'en';
  setLanguage(savedLang);
  
  // Setup click triggers on language switch buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const targetLang = btn.getAttribute('data-lang');
      setLanguage(targetLang);
    });
  });
});
